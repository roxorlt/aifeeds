import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ucd = resolve(root, 'vendor/unicode/15.1.0/ucd');
const output = resolve(root, 'src/digest/manual-news-unicode15.generated.ts');

function lines(relative) {
  return readFileSync(resolve(ucd, relative), 'utf8').split(/\r?\n/u);
}

function parseRange(value) {
  const [first, last = first] = value.trim().split('..');
  return [Number.parseInt(first, 16), Number.parseInt(last, 16)];
}

function propertyRanges(relative, predicate) {
  return lines(relative).flatMap((line) => {
    const content = line.replace(/#.*/u, '').trim();
    if (!content) return [];
    const [range, property, value] = content.split(';').map((part) => part.trim());
    return predicate(property, value) ? [[...parseRange(range), value || property]] : [];
  });
}

const ccc = {};
const canonicalDecomposition = {};
const compatibilityDecomposition = {};
for (const line of lines('UnicodeData.txt')) {
  const fields = line.split(';');
  if (fields.length !== 15) continue;
  const codePoint = Number.parseInt(fields[0], 16);
  const combiningClass = Number.parseInt(fields[3], 10);
  if (combiningClass) ccc[codePoint] = combiningClass;
  const mapping = fields[5].trim().split(' ').filter(Boolean);
  if (mapping.length) {
    const compatibility = mapping[0].startsWith('<') ? mapping.slice(1) : mapping;
    compatibilityDecomposition[codePoint] = compatibility.map((value) => Number.parseInt(value, 16));
    if (!mapping[0].startsWith('<')) {
      canonicalDecomposition[codePoint] = compatibility.map((value) => Number.parseInt(value, 16));
    }
  }
}

const excluded = new Set();
for (const line of lines('CompositionExclusions.txt')) {
  const content = line.replace(/#.*/u, '').trim();
  if (content) excluded.add(Number.parseInt(content, 16));
}
for (const [first, last] of propertyRanges('DerivedNormalizationProps.txt', (property) =>
  property === 'Full_Composition_Exclusion')) {
  for (let codePoint = first; codePoint <= last; codePoint += 1) excluded.add(codePoint);
}

const composition = {};
for (const [target, mapping] of Object.entries(canonicalDecomposition)) {
  if (mapping.length === 2 && !excluded.has(Number(target))) {
    composition[`${mapping[0]}/${mapping[1]}`] = Number(target);
  }
}

const grapheme = propertyRanges('auxiliary/GraphemeBreakProperty.txt', () => true)
  .map(([first, last, value]) => [first, last, value])
  .sort((left, right) => left[0] - right[0]);
const extendedPictographic = propertyRanges('emoji/emoji-data.txt', (property) => property === 'Extended_Pictographic')
  .map(([first, last]) => [first, last])
  .sort((left, right) => left[0] - right[0]);
const indicConjunct = propertyRanges('DerivedCoreProperties.txt', (property) => property === 'InCB')
  .map(([first, last, value]) => [first, last, value])
  .sort((left, right) => left[0] - right[0]);

const generated = `// Generated by scripts/generate-unicode15-tables.mjs from vendored Unicode 15.1.0 UCD data.\n`
  + `// Do not edit manually. Regenerate after updating the provenance manifest.\n\n`
  + `export const UNICODE_15_1_CANONICAL_COMBINING_CLASS: Readonly<Record<number, number>> = ${JSON.stringify(ccc)};\n\n`
  + `export const UNICODE_15_1_CANONICAL_DECOMPOSITION: Readonly<Record<number, readonly number[]>> = ${JSON.stringify(canonicalDecomposition)};\n\n`
  + `export const UNICODE_15_1_COMPATIBILITY_DECOMPOSITION: Readonly<Record<number, readonly number[]>> = ${JSON.stringify(compatibilityDecomposition)};\n\n`
  + `export const UNICODE_15_1_CANONICAL_COMPOSITION: Readonly<Record<string, number>> = ${JSON.stringify(composition)};\n\n`
  + `export type Unicode15Range<T extends string = string> = readonly [first: number, last: number, value: T];\n\n`
  + `export const UNICODE_15_1_GRAPHEME_BREAK: readonly Unicode15Range[] = ${JSON.stringify(grapheme)};\n\n`
  + `export const UNICODE_15_1_EXTENDED_PICTOGRAPHIC: readonly (readonly [first: number, last: number])[] = ${JSON.stringify(extendedPictographic)};\n\n`
  + `export const UNICODE_15_1_INDIC_CONJUNCT_BREAK: readonly Unicode15Range[] = ${JSON.stringify(indicConjunct)};\n`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, generated, 'utf8');
